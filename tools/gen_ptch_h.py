#!/usr/bin/env python3
"""data/ptch/*.txt -> src/skptch.h (note -> PTCH tables, ends clamped, 255 = voice has no table)."""
import glob, os
out=["/* generated by tools/gen_ptch_h.py from data/ptch - do not edit */",
     "static const struct { const char *name; unsigned char lo, hi; unsigned char tab[128]; } sk_ptch_tables[] = {"]
for fn in sorted(glob.glob('data/ptch/*.txt')):
    n=os.path.basename(fn)[:-4]; t={}
    for l in open(fn):
        l=l.strip().rstrip(';')
        if l: a,b=l.split(); t[int(a)]=int(b)
    lo,hi=min(t),max(t)
    tab=[t[min(max(m,lo),hi)] for m in range(128)]
    out.append(f'  {{ "{n}", {lo}, {hi}, {{'+",".join(map(str,tab))+"} },")
out.append("};")
open('src/skptch.h','w').write("\n".join(out)+"\n")
print(len(out)-3,"tables")
